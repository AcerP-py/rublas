// ===========================================================================
// SFLOAT
// ===========================================================================
pub type SFLOAT = f32;

// ===========================================================================
// DFLOAT
// ===========================================================================
pub type DFLOAT = f64;

#[cfg(test)]
mod test {
    use super::*;

    #[test]
    fn sfloat_basic() {
        let x: SFLOAT = 3.45;
        assert_eq!(x, 3.45);
    }

    #[test]
    fn dfloat_basic() {
        let x: DFLOAT = 3.45;
        assert_eq!(x, 3.45);
    }
}
