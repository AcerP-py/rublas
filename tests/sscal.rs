use rublas::{SFLOAT, sscal};

#[test]
fn sscal_basic() {
    let mut y: [SFLOAT; 10] = [21.0, 22.0, 23.0, 24.0, 25.0, 26.0, 27.0, 28.0, 29.0, 30.0];

    sscal(10, 2.0, &mut y, 1);
    assert_eq!(y[2], 46.0);

    y = [21.0, 22.0, 23.0, 24.0, 25.0, 26.0, 27.0, 28.0, 29.0, 30.0];
    sscal(4, 2.0, &mut y, 1);
    assert_eq!(y[2], 46.0);

    y = [21.0, 22.0, 23.0, 24.0, 25.0, 26.0, 27.0, 28.0, 29.0, 30.0];
    sscal(0, 2.0, &mut y, 1);
    assert_eq!(y[2], 23.0);

    y = [21.0, 22.0, 23.0, 24.0, 25.0, 26.0, 27.0, 28.0, 29.0, 30.0];
    sscal(5, 2.0, &mut y, 2);
    assert_eq!(y[4], 50.0);
}
